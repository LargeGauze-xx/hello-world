# 练习：嵌套列表（二维表）

students = [
    ["小明", 85, 92, 78],
    ["小红", 90, 88, 95],
    ["小刚", 72, 80, 85],
]
# 如果要取嵌套表中的数值，需要进行两次取出[x][y]
print(students[1][2])
# 如果要计算嵌套表的数据，那么就需要先将原表进行一次遍历
# 得到了新标签后再对新标签进行遍历以取出数值而不是序列
for row in students:
    # 注意total的位置！！！
    # 1.放在最外面相当于累加计算总值
    # 2.放在外层循环里、内层循环之外相当于计算每个标签的总值
    # 3.放在最里面相当于每变化一次就清除一次，之后留下最后的值
    total=0
# 注意遍历的取值要取到数字才能进行计算
    for s in row[1:]:
        total=total+s
    print(row[0],total)
