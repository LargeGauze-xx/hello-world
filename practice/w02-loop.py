# for代表开始循环，i为循环的变量，range是循环的值
# 如果是range(5)的意思是从 0 开始、到 5 之前（0，1，2，3，4）
# 如果是range(1，6)的意思是从 1 开始、到 6 之前（1，2，3，4，5）
print("=== 九九乘法表 ===")

# 外层：i 是行号，从 1 到 9
for i in range(1,10):
    # 内层：j 是这一行第几个，从 1 到 i（所以每行越来越长）
    for j in range(1,i+1):
        # 打印 j*i=积；end="\t" 表示不换行、用制表符隔开
        print(f"{j}*{i}={j*i}",end="\t")
    # 内层结束 → 换行（这行缩进 4 格，属于外层）
    print()